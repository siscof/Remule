"""Generate src/codes.rs from aMule's ECCodes.abstract and ECTagTypes.abstract.

Usage: python gen_codes.py <amule>/src/libs/ec/abstracts > src/codes.rs

The constant names are kept exactly as in the C++ headers (EC_OP_*, EC_TAG_*,
...) so that a grep for a name finds both sides of the port.
"""
import re
import sys
from pathlib import Path

RUST_TYPES = {"uint8": "u8", "uint16": "u16", "uint32": "u32", "uint64": "u64"}


def sections(text):
    for m in re.finditer(r"\[Section Content\](.*?)\[/Section\]", text, re.S):
        body = m.group(1)
        kind = re.search(r"^Type\s+(\S+)", body, re.M).group(1)
        if kind != "Enum":
            continue
        name = re.search(r"^Name\s+(\S+)", body, re.M).group(1)
        dtype = re.search(r"^DataType\s+(\S+)", body, re.M).group(1)
        entries = []
        for line in body.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) >= 2 and parts[0].startswith("EC_") and re.match(r"^(0x[0-9a-fA-F]+|\d+)$", parts[1]):
                entries.append((parts[0], parts[1]))
        yield name, RUST_TYPES[dtype], entries


def main():
    root = Path(sys.argv[1])
    out = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "//! EC protocol constants.",
        "//!",
        "//! GENERATED by `gen_codes.py` from aMule's `ECCodes.abstract` and",
        "//! `ECTagTypes.abstract`. Do not edit by hand; regenerate instead.",
        "#![allow(missing_docs, dead_code)]",
        "",
    ]
    for fname in ("ECCodes.abstract", "ECTagTypes.abstract"):
        text = (root / fname).read_text(encoding="utf-8")
        for name, rtype, entries in sections(text):
            out.append(f"// --- {name} ({rtype}) ---")
            for ident, value in entries:
                out.append(f"pub const {ident}: {rtype} = {value};")
            out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
